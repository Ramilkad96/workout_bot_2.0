def _as_tuple(version: str) -> tuple:
    try:
        return tuple(int(part) for part in str(version).split("."))
    except (TypeError, ValueError):
        return (0,)


def releases_since(seen_version: str | None) -> list:
    """Обновления, которые пользователь ещё не видел (новые сверху).

    Пустая версия — это пользователь, заведённый до появления уведомлений:
    вываливать ему всю историю не нужно, показываем только последнее.
    """
    if not seen_version:
        return RELEASES[:1]
    seen = _as_tuple(seen_version)
    return [r for r in RELEASES if _as_tuple(r["version"]) > seen]


def format_releases(releases: list, header: str = "🆕 Что нового") -> str:
    lines = [header, ""]
    for release in releases:
        lines.append(f"Версия {release['version']} — {release['title']}")
        lines.append(f"({release['date']})")
        for change in release["changes"]:
            lines.append(f"• {change}")
        lines.append("")
    return "\n".join(lines).strip()


def latest() -> dict:
    return RELEASES[0]
