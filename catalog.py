def group_names() -> list:
    return [name for name, _ in CATALOG]


def exercises_of(group_index: int) -> list:
    return CATALOG[group_index][1]


def group_name(group_index: int) -> str:
    return CATALOG[group_index][0]


def exercise_name(group_index: int, exercise_index: int) -> str:
    return CATALOG[group_index][1][exercise_index]


def is_valid(group_index: int, exercise_index: int | None = None) -> bool:
    if not (0 <= group_index < len(CATALOG)):
        return False
    if exercise_index is None:
        return True
    return 0 <= exercise_index < len(CATALOG[group_index][1])
